/**
 * Luna the dog for the slave OLED, rotated 270 (portrait 32x128).
 *
 * Frame data and pose logic taken verbatim from @filterpaper's oled_luna.c
 * (https://github.com/filterpaper/qmk_oled_animations), which is itself a
 * rework of @HellSingCoder's Luna dog from the Sofle "helltm" keymap.
 * Removed: the Corne logo/status rendering and the oled_init_user /
 * oled_task_user hooks, since keymap.c owns those here.
 *
 * Cost: one 96-byte oled_write_raw_P every LUNA_FRAME_DURATION ms, touching a
 * 32x24 region. No per-pixel loops, no full-framebuffer sweep, no reseed
 * spikes. 10 frames x 96B = 960 bytes of PROGMEM.
 *
 * Pose is driven by mods, caps and typing speed, so config.h needs
 * SPLIT_MODS_ENABLE, SPLIT_LED_STATE_ENABLE and SPLIT_ACTIVITY_ENABLE for the
 * slave half to see any of it.
 */

